"""
Короткие реплики без вопроса — готовый ответ без похода в LLM (П2/П6 из docs/bot-testing.md).

Модель на «привет» или «???» иногда отвечала «По базе не нашёл ответа»: поиск по базе ничего не находил,
и срабатывало правило отказа. Промпт это уже различает (rag_context.j2), а здесь — дешёвая и детерминированная
страховка: сообщение целиком из приветствия/благодарности/«старт» или из одних знаков и эмодзи отвечается сразу.
Всё длиннее («привет, сколько вернут за лечение?») уходит в backend как обычно.
"""

import re

EXAMPLES = (
    "Например:\n"
    "• «Сколько можно вернуть за лечение зубов?»\n"
    "• «До какой суммы страхуются вклады?»\n"
    "• «Доход 80 000, расходы 65 000 — сколько получится отложить за год?»"
)

_GREETING = "Здравствуйте! Я Финпомощник — помогаю с личными финансами: налоги и вычеты, вклады, кредиты, бюджет, " \
            "защита от мошенников. Задайте вопрос или выберите кнопку внизу.\n\n" + EXAMPLES
_THANKS = "Пожалуйста! Если появятся ещё вопросы о деньгах — пишите."
_OK = "Хорошо. Если будут вопросы — пишите, я на связи."
_UNCLEAR = "Не понял вопрос — напишите, пожалуйста, подробнее.\n\n" + EXAMPLES

_PHRASES: dict[str, str] = {}
for _reply, _words in (
    (_GREETING, ("привет", "приветик", "здравствуй", "здравствуйте", "здрасте", "добрый день", "доброе утро",
                 "добрый вечер", "доброй ночи", "хай", "hi", "hello", "hey", "салют", "старт", "start", "начать",
                 "начнем", "начнём", "меню", "помощь", "help", "алло", "ау", "эй", "ты тут", "ты здесь")),
    (_THANKS, ("спасибо", "спасибо большое", "благодарю", "спс", "thanks", "thank you", "пасиб", "мерси")),
    (_OK, ("ок", "окей", "ok", "okay", "хорошо", "понятно", "понял", "поняла", "ясно", "ага", "угу", "отлично",
           "супер", "класс")),
):
    for _w in _words:
        _PHRASES[_w.replace("ё", "е")] = _reply

_NON_WORD = re.compile(r"[^\w\s]+|_")
_APPROVAL_EMOJI = set("👍👌🙏❤✅😊🙂😀😃🤝💪🔥👏")  # 👍 после ответа — это «ок», а не непонятный вопрос


def canned_reply(text: str | None) -> str | None:
    """Готовый ответ на короткую реплику или None — тогда сообщение уходит в backend."""
    if not text:
        return None
    words = _NON_WORD.sub(" ", text.lower().replace("ё", "е")).split()
    if not words:  # одни знаки и эмодзи
        return _OK if _APPROVAL_EMOJI & set(text) else _UNCLEAR  # «👍» — «ок»; «???», «🤔» — не понял
    return _PHRASES.get(" ".join(words))
