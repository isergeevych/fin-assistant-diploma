def main() -> None:
    raw = pd.read_csv(ROOT / "tests" / "eval" / "golden_dataset_raw.csv")
    contexts = [ast.literal_eval(c) for c in raw["reference_contexts"]]
    items = []
    for i, row in raw.iterrows():
        if i in DROP:
            continue
        edit = EDIT.get(i, {})
        ctx = contexts[edit.get("reference_contexts_from", i)]
        if "reference_contexts_keep" in edit:
            ctx = [ctx[k] for k in edit["reference_contexts_keep"]]
        items.append({
            "id": f"g{len(items) + 1:02d}",
            "type": "single_hop" if row["synthesizer_name"].startswith("single") else "multi_hop",
            "user_input": edit.get("user_input", row["user_input"]),
            "reference": edit.get("reference", row["reference"]),
            "reference_contexts": [c.split("> ", 1)[-1] if c.startswith("<") else c for c in ctx],
            "source_row": int(i),
            "review_note": edit.get("note", "без правок"),
        })
    for neg in NEGATIVE:
        items.append({"id": f"g{len(items) + 1:02d}", "type": "out_of_scope", **neg, "reference_contexts": [],
                      "source_row": None, "review_note": "добавлен вручную: проверка честного отказа"})
    golden = {"version": 1, "source": "RAGAS TestsetGenerator (gpt-5.4-mini) + ручная вычитка scripts/curate_golden.py",
              "dropped": {str(k): v for k, v in DROP.items()}, "items": items}
    out = ROOT / "tests" / "eval" / "golden_dataset.json"
    out.write_text(json.dumps(golden, ensure_ascii=False, indent=2), encoding="utf-8")
    edited = sum(1 for i in items if i["review_note"] != "без правок")
    print(f"{len(raw)} сырых → удалено {len(DROP)}, правок {edited}, итого {len(items)} пар → {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
